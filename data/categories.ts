export function getCategoryById(id: string): CategoryNode | undefined {
  return CATEGORIES.find((c) => c.id === id);
}

export function getSubcategoryTitle(mainId: string, subId: string): string {
  const main = getCategoryById(mainId);
  if (!main) return subId;
  return main.children.find((c) => c.id === subId)?.title ?? subId;
}
